CREATE TABLE usuario (
  id          INT          GENERATED BY DEFAULT AS IDENTITY,
  nome        VARCHAR(120) NOT NULL,
  email       VARCHAR(120) NOT NULL,
  senha_hash  VARCHAR(255) NOT NULL,
  telefone    VARCHAR(20)  NULL,
  perfil      VARCHAR(20)  NOT NULL,
  ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
  criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_usuario PRIMARY KEY (id),
  CONSTRAINT uk_usuario_email UNIQUE (email),
  CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMINISTRADOR', 'DOADOR', 'ENTIDADE'))
);

CREATE TABLE doador (
  id           INT          GENERATED BY DEFAULT AS IDENTITY,
  usuario_id   INT          NOT NULL,
  tipo_pessoa  VARCHAR(10)  NOT NULL,
  documento    VARCHAR(18)  NOT NULL,
  endereco     VARCHAR(200) NULL,
  CONSTRAINT pk_doador PRIMARY KEY (id),
  CONSTRAINT uk_doador_usuario UNIQUE (usuario_id),
  CONSTRAINT uk_doador_documento UNIQUE (documento),
  CONSTRAINT ck_doador_tipo CHECK (tipo_pessoa IN ('FISICA', 'JURIDICA')),
  CONSTRAINT fk_doador_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE TABLE entidade (
  id                 INT          GENERATED BY DEFAULT AS IDENTITY,
  usuario_id         INT          NOT NULL,
  cnpj               VARCHAR(18)  NOT NULL,
  endereco           VARCHAR(200) NOT NULL,
  responsavel        VARCHAR(120) NOT NULL,
  pessoas_atendidas  INT          NOT NULL,
  aprovada           BOOLEAN      NOT NULL DEFAULT FALSE,
  CONSTRAINT pk_entidade PRIMARY KEY (id),
  CONSTRAINT uk_entidade_usuario UNIQUE (usuario_id),
  CONSTRAINT uk_entidade_cnpj UNIQUE (cnpj),
  CONSTRAINT ck_entidade_pessoas CHECK (pessoas_atendidas > 0),
  CONSTRAINT fk_entidade_usuario FOREIGN KEY (usuario_id)
    REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE TABLE doacao (
  id            INT          GENERATED BY DEFAULT AS IDENTITY,
  doador_id     INT          NOT NULL,
  data_doacao   DATE         NOT NULL,
  situacao      VARCHAR(10)  NOT NULL DEFAULT 'PENDENTE',
  recebida_em   TIMESTAMP    NULL,
  recebida_por  INT          NULL,
  observacao    VARCHAR(255) NULL,
  CONSTRAINT pk_doacao PRIMARY KEY (id),
  CONSTRAINT ck_doacao_situacao CHECK (situacao IN ('PENDENTE', 'RECEBIDA', 'RECUSADA', 'CANCELADA')),
  CONSTRAINT fk_doacao_doador FOREIGN KEY (doador_id)
    REFERENCES doador (id),
  CONSTRAINT fk_doacao_admin FOREIGN KEY (recebida_por)
    REFERENCES usuario (id)
);

CREATE INDEX idx_doacao_situacao ON doacao (situacao);

CREATE TABLE alimento (
  id              INT           GENERATED BY DEFAULT AS IDENTITY,
  doacao_id       INT           NOT NULL,
  nome            VARCHAR(100)  NOT NULL,
  categoria       VARCHAR(12)   NOT NULL,
  quantidade      NUMERIC(10,2) NOT NULL,
  unidade         VARCHAR(10)   NOT NULL,
  validade        DATE          NOT NULL,
  qtd_disponivel  NUMERIC(10,2) NOT NULL DEFAULT 0,
  CONSTRAINT pk_alimento PRIMARY KEY (id),
  CONSTRAINT ck_alimento_categoria CHECK (categoria IN ('GRAOS', 'ENLATADOS', 'LATICINIOS', 'CARNES', 'HORTIFRUTI', 'BEBIDAS', 'OUTROS')),
  CONSTRAINT ck_alimento_unidade CHECK (unidade IN ('KG', 'G', 'L', 'ML', 'UNIDADE', 'PACOTE', 'CAIXA')),
  CONSTRAINT ck_alimento_quantidade CHECK (quantidade > 0),
  CONSTRAINT ck_alimento_disponivel CHECK (qtd_disponivel >= 0 AND qtd_disponivel <= quantidade),
  CONSTRAINT fk_alimento_doacao FOREIGN KEY (doacao_id)
    REFERENCES doacao (id) ON DELETE CASCADE
);

CREATE INDEX idx_alimento_validade ON alimento (validade);

CREATE TABLE solicitacao (
  id                INT          GENERATED BY DEFAULT AS IDENTITY,
  entidade_id       INT          NOT NULL,
  data_solicitacao  DATE         NOT NULL,
  situacao          VARCHAR(10)  NOT NULL DEFAULT 'PENDENTE',
  avaliada_por      INT          NULL,
  data_entrega      DATE         NULL,
  motivo_recusa     VARCHAR(255) NULL,
  CONSTRAINT pk_solicitacao PRIMARY KEY (id),
  CONSTRAINT ck_solicitacao_situacao CHECK (situacao IN ('PENDENTE', 'APROVADA', 'RECUSADA', 'ENTREGUE', 'CANCELADA')),
  CONSTRAINT fk_solicitacao_entidade FOREIGN KEY (entidade_id)
    REFERENCES entidade (id),
  CONSTRAINT fk_solicitacao_admin FOREIGN KEY (avaliada_por)
    REFERENCES usuario (id)
);

CREATE INDEX idx_solicitacao_situacao ON solicitacao (situacao);

CREATE TABLE item_solicitacao (
  id              INT           GENERATED BY DEFAULT AS IDENTITY,
  solicitacao_id  INT           NOT NULL,
  alimento_id     INT           NOT NULL,
  quantidade      NUMERIC(10,2) NOT NULL,
  CONSTRAINT pk_item_solicitacao PRIMARY KEY (id),
  CONSTRAINT uk_item_solicitacao UNIQUE (solicitacao_id, alimento_id),
  CONSTRAINT ck_item_quantidade CHECK (quantidade > 0),
  CONSTRAINT fk_item_solicitacao FOREIGN KEY (solicitacao_id)
    REFERENCES solicitacao (id) ON DELETE CASCADE,
  CONSTRAINT fk_item_alimento FOREIGN KEY (alimento_id)
    REFERENCES alimento (id)
);

CREATE VIEW vw_estoque AS
SELECT a.id, a.nome, a.categoria, a.qtd_disponivel, a.unidade, a.validade
FROM alimento a
JOIN doacao d ON d.id = a.doacao_id
WHERE d.situacao = 'RECEBIDA'
  AND a.qtd_disponivel > 0
  AND a.validade >= CURRENT_DATE
ORDER BY a.validade;
